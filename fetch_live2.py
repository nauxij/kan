def sort_channels(channels):
    order_map = {name: idx for idx, name in enumerate(ORDER_LIST)}
    def sort_key(chan):
        name = chan.get("name", "")
        return order_map.get(name, 99999)
    return sorted(channels, key=sort_key)

def fetch_file():
    url = "https://gitee.com/x21y/yx/raw/main/qdyd.nzk"
    out_file = "qdyd.nzk"
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
    }
    try:
        resp = requests.get(url, headers=headers, timeout=30)
        resp.raise_for_status()
        with open(out_file, "wb") as f:
            f.write(resp.content)
        print(f"已下载 {out_file}")

        with open(out_file, "r", encoding="utf-8") as f:
            data = json.load(f)
        if "channels" in data:
            old_list = data["channels"]
            new_list = sort_channels(old_list)
            data["channels"] = new_list
            print(f"排序完成，共{len(old_list)}频道")
        with open(out_file, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"已输出排序后的 {out_file}")
    except Exception as e:
        print(f"错误：{e}")

if __name__ == "__main__":
    fetch_file()
